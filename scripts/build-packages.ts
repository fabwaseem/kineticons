// Writes the per-icon modules of the framework packages from the core icon set:
//   packages/react/src/icons.ts    export const Bell = createIcon(bell, "Bell"); (and BellIcon)
//   packages/vue/src/icons.ts      the same for Vue
//   packages/svelte/src/lib/icons.ts   the icon data, re-exported
// Run after `pnpm import-icons` (the package builds run it too).
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ICONS } from "../packages/core/src/all-icons";

const root = join(import.meta.dirname, "..");
const RESERVED = new Set(["package", "private", "public", "import", "export", "default", "delete", "new", "class", "function", "return", "switch", "case", "break", "continue", "var", "let", "const", "if", "else", "for", "while", "do", "in", "of", "this", "super", "throw", "try", "catch", "finally", "typeof", "void", "with", "yield", "enum", "interface", "static", "protected", "implements", "await", "null", "true", "false"]);
const camelOf = (n: string) => n.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const dataId = (n: string) => (RESERVED.has(camelOf(n)) ? camelOf(n) + "Icon" : camelOf(n));
const pascal = (n: string) => camelOf(n).replace(/^./, (c) => c.toUpperCase());

const names = ICONS.map((i) => i.name).sort();
const comps = new Map<string, string>();
for (const n of names) {
  const p = pascal(n);
  if (comps.has(p)) throw new Error(`two icons make the component name ${p}: ${comps.get(p)} and ${n}`);
  comps.set(p, n);
}
/** BellIcon next to Bell, unless that name is an icon of its own */
const alias = (p: string) => (comps.has(p + "Icon") || p.endsWith("Icon") ? null : p + "Icon");

const header = "// Generated by scripts/build-packages.ts from the core icon set: do not edit.\n";
const imports = `import {\n${names.map((n) => `  ${dataId(n)},`).join("\n")}\n} from "@kineticons/core/icons";\n`;
const body = (fn: string) =>
  names
    .map((n) => {
      const p = pascal(n);
      const a = alias(p);
      return `/** ${ICONS.find((i) => i.name === n)!.title}: ${n} */\nexport const ${p} = /*#__PURE__*/ ${fn}(${dataId(n)}, "${p}");${a ? `\nexport { ${p} as ${a} };` : ""}`;
    })
    .join("\n");

writeFileSync(join(root, "packages/react/src/icons.ts"), `${header}import { createIcon } from "./KineticIcon";\n${imports}\n${body("createIcon")}\n`);
writeFileSync(join(root, "packages/vue/src/icons.ts"), `${header}import { createIcon } from "./KineticIcon";\n${imports}\n${body("createIcon")}\n`);
writeFileSync(join(root, "packages/svelte/src/lib/icons.ts"), `${header}export * from "@kineticons/core/icons";\n`);
console.log(`${names.length} icons: react, vue and svelte modules written`);

// the website: icon counts, so a page can show them without loading the catalog
const byCategory: Record<string, number> = {};
for (const i of ICONS) byCategory[i.category] = (byCategory[i.category] ?? 0) + 1;
writeFileSync(
  join(root, "apps/web/lib/stats.generated.ts"),
  `${header}export const ICON_COUNT = ${ICONS.length};\nexport const CATEGORY_COUNTS: Record<string, number> = ${JSON.stringify(byCategory)};\n`,
);
